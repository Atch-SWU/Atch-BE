
-- AI 시간 예측 전략 비교 및 실험 로그
CREATE TABLE time_prediction_experiments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prediction_run_id UUID NOT NULL,
    todo_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    strategy_type VARCHAR(40) NOT NULL,
    predicted_minutes INTEGER NOT NULL,
    actual_minutes INTEGER,
    absolute_error_minutes INTEGER,
    absolute_percentage_error DOUBLE PRECISION,
    baseline_prediction_minutes INTEGER,
    duration_correction_factor DOUBLE PRECISION,
    simple_factor DOUBLE PRECISION,
    profile_reliability_score DOUBLE PRECISION,
    sample_count INTEGER,
    log_ratio_stddev DOUBLE PRECISION,
    underestimation_rate DOUBLE PRECISION,
    context_adjustment_factor DOUBLE PRECISION,
    similar_todo_ids JSONB,
    reason_codes JSONB,
    model_name VARCHAR(100),
    prompt_version VARCHAR(50),
    embedding_model VARCHAR(100),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    evaluated_at TIMESTAMPTZ,

    CONSTRAINT fk_time_prediction_experiments_todo
        FOREIGN KEY (todo_id) REFERENCES todos(id),

    CONSTRAINT fk_time_prediction_experiments_user
        FOREIGN KEY (user_id) REFERENCES users(id),

    CONSTRAINT ck_time_prediction_experiments_strategy
        CHECK (
            strategy_type IN (
                'USER_ESTIMATE',
                'SIMPLE_FACTOR',
                'STATISTICAL_BASELINE',
                'HYBRID'
            )
        ),

    CONSTRAINT ck_time_prediction_experiments_predicted
        CHECK (predicted_minutes > 0),

    CONSTRAINT ck_time_prediction_experiments_actual
        CHECK (actual_minutes IS NULL OR actual_minutes >= 0),

    CONSTRAINT ck_time_prediction_experiments_absolute_error
        CHECK (
            absolute_error_minutes IS NULL
            OR absolute_error_minutes >= 0
        ),

    CONSTRAINT ck_time_prediction_experiments_percentage_error
        CHECK (
            absolute_percentage_error IS NULL
            OR absolute_percentage_error >= 0
        ),

    CONSTRAINT ck_time_prediction_experiments_sample_count
        CHECK (sample_count IS NULL OR sample_count >= 0),

    CONSTRAINT ck_time_prediction_experiments_json_arrays
        CHECK (
            (similar_todo_ids IS NULL
                OR jsonb_typeof(similar_todo_ids) = 'array')
            AND
            (reason_codes IS NULL
                OR jsonb_typeof(reason_codes) = 'array')
        )
);

-- 동일 예측 실행의 전략별 기록 조회
CREATE INDEX ix_time_prediction_experiments_run
    ON time_prediction_experiments (prediction_run_id);

-- Todo별 예측 실험 이력 조회
CREATE INDEX ix_time_prediction_experiments_todo_user_created
    ON time_prediction_experiments (
        todo_id, user_id, created_at DESC, id DESC
    );

-- 사용자별 평가 완료 전략 조회
CREATE INDEX ix_time_prediction_experiments_evaluated_strategy
    ON time_prediction_experiments (user_id, strategy_type)
    WHERE evaluated_at IS NOT NULL;
