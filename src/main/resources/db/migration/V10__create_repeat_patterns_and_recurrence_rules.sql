
-- 반복 패턴 및 반복 일정 규칙
-- 기존 V1~V9는 변경하지 않음

-- V10 이전에는 RecurrenceRule 테이블이 없으므로 기존 반복 참조는 없어야 함
-- 예상하지 못한 데이터가 있으면 자동 보정하지 않고 마이그레이션 중단
DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM todos
        WHERE recurrence_rule_id IS NOT NULL
    ) THEN
        RAISE EXCEPTION
            'V10 migration aborted: existing recurrence references require review';
    END IF;
END
$$;


-- 1. 반복 패턴
CREATE TABLE repeat_patterns (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    task_name VARCHAR(200) NOT NULL,
    frequency VARCHAR(20) NOT NULL,
    day_of_week VARCHAR(10),
    scheduled_time TIME NOT NULL,
    occurrence_count INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL,
    last_occurrence_date DATE NOT NULL,
    last_suggested_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_repeat_patterns_user
        FOREIGN KEY (user_id) REFERENCES users(id),

    -- RecurrenceRule에서 패턴과 사용자를 함께 참조하기 위한 고유성
    CONSTRAINT uq_repeat_patterns_id_user
        UNIQUE (id, user_id),

    CONSTRAINT ck_repeat_patterns_task_name
        CHECK (char_length(btrim(task_name)) > 0),

    CONSTRAINT ck_repeat_patterns_frequency
        CHECK (frequency IN ('DAILY', 'WEEKLY')),

    -- DAILY는 요일 없음, WEEKLY는 유효한 요일 필수
    CONSTRAINT ck_repeat_patterns_day_of_week
        CHECK (
            (frequency = 'DAILY' AND day_of_week IS NULL)
            OR
            (
                frequency = 'WEEKLY'
                AND day_of_week IS NOT NULL
                AND day_of_week IN (
                    'MONDAY',
                    'TUESDAY',
                    'WEDNESDAY',
                    'THURSDAY',
                    'FRIDAY',
                    'SATURDAY',
                    'SUNDAY'
                )
            )
        ),

    CONSTRAINT ck_repeat_patterns_occurrence_count
        CHECK (occurrence_count > 0),

    CONSTRAINT ck_repeat_patterns_status
        CHECK (
            status IN (
                'DETECTING',
                'SUGGESTED',
                'DISMISSED',
                'REGISTERED'
            )
        )
);

-- 사용자별 패턴 상태 및 최근 추천 내역 조회
CREATE INDEX ix_repeat_patterns_user_status
    ON repeat_patterns (
        user_id,
        status,
        last_suggested_at DESC,
        id DESC
    );


-- 2. 반복 일정 규칙
CREATE TABLE recurrence_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    source_pattern_id BIGINT NOT NULL,
    task_name VARCHAR(200) NOT NULL,
    memo TEXT,
    frequency VARCHAR(20) NOT NULL,
    day_of_week VARCHAR(10),
    scheduled_time TIME NOT NULL,
    default_deadline_offset_minutes INTEGER NOT NULL,
    default_user_estimated_duration_minutes INTEGER NOT NULL,
    enabled BOOLEAN NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMPTZ,

    CONSTRAINT fk_recurrence_rules_user
        FOREIGN KEY (user_id) REFERENCES users(id),

    -- 하나의 감지 패턴에서 규칙을 최대 하나만 생성
    -- 논리 삭제된 규칙도 원본 패턴을 계속 점유
    CONSTRAINT uq_recurrence_rules_source_pattern
        UNIQUE (source_pattern_id),

    -- Todo에서 규칙과 사용자를 함께 참조하기 위한 고유성
    CONSTRAINT uq_recurrence_rules_id_user
        UNIQUE (id, user_id),

    -- 원본 패턴과 규칙의 소유 사용자가 반드시 일치해야 함
    CONSTRAINT fk_recurrence_rules_pattern_owner
        FOREIGN KEY (source_pattern_id, user_id)
        REFERENCES repeat_patterns (id, user_id),

    CONSTRAINT ck_recurrence_rules_task_name
        CHECK (char_length(btrim(task_name)) > 0),

    CONSTRAINT ck_recurrence_rules_frequency
        CHECK (frequency IN ('DAILY', 'WEEKLY')),

    -- DAILY는 요일 없음, WEEKLY는 유효한 요일 필수
    CONSTRAINT ck_recurrence_rules_day_of_week
        CHECK (
            (frequency = 'DAILY' AND day_of_week IS NULL)
            OR
            (
                frequency = 'WEEKLY'
                AND day_of_week IS NOT NULL
                AND day_of_week IN (
                    'MONDAY',
                    'TUESDAY',
                    'WEDNESDAY',
                    'THURSDAY',
                    'FRIDAY',
                    'SATURDAY',
                    'SUNDAY'
                )
            )
        ),

    CONSTRAINT ck_recurrence_rules_deadline_offset
        CHECK (default_deadline_offset_minutes > 0),

    CONSTRAINT ck_recurrence_rules_user_estimate
        CHECK (default_user_estimated_duration_minutes > 0)
);

-- 사용자별 등록 규칙 및 활성 여부 조회
CREATE INDEX ix_recurrence_rules_user_active
    ON recurrence_rules (user_id, enabled, id)
    WHERE deleted_at IS NULL;


-- 3. 기존 Todo 테이블 확장
-- 반복 회차의 논리적 기준 날짜
-- DAILY: 해당 날짜, WEEKLY: 해당 ISO 주의 월요일
ALTER TABLE todos
    ADD COLUMN recurrence_period_start_date DATE;

-- 반복 규칙 ID와 논리적 회차 날짜는 함께 존재해야 함
-- 기존 V4의 ck_todos_recurrence_pair는 그대로 유지
ALTER TABLE todos
    ADD CONSTRAINT ck_todos_recurrence_period_pair
    CHECK (
        (
            recurrence_rule_id IS NULL
            AND recurrence_period_start_date IS NULL
        )
        OR
        (
            recurrence_rule_id IS NOT NULL
            AND recurrence_period_start_date IS NOT NULL
        )
    );

-- 논리 삭제된 Todo도 이미 생성된 회차로 취급
-- 같은 규칙에서 같은 날짜·주간 회차의 중복 생성 방지
CREATE UNIQUE INDEX uq_todos_recurrence_period
    ON todos (
        recurrence_rule_id,
        recurrence_period_start_date
    )
    WHERE recurrence_rule_id IS NOT NULL;

-- Todo와 반복 규칙의 사용자 소유권 일치 보장
ALTER TABLE todos
    ADD CONSTRAINT fk_todos_recurrence_rule_owner
    FOREIGN KEY (recurrence_rule_id, user_id)
    REFERENCES recurrence_rules (id, user_id);
