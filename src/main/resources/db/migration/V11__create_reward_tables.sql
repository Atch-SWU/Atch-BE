
-- 캐릭터 아이템·보유·장착·일일 보상 정산·지급 이력
-- 기존 V1~V10 마이그레이션은 변경하지 않음


-- 1. 캐릭터 아이템 카탈로그
CREATE TABLE character_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    grade VARCHAR(10) NOT NULL,
    category VARCHAR(20) NOT NULL,
    asset_key VARCHAR(500) NOT NULL,
    active BOOLEAN NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- 장착 카테고리 및 지급 등급 복합 FK의 참조 대상
    CONSTRAINT uq_character_items_id_category
        UNIQUE (id, category),

    CONSTRAINT uq_character_items_id_grade
        UNIQUE (id, grade),

    CONSTRAINT ck_character_items_name
        CHECK (char_length(btrim(name)) > 0),

    CONSTRAINT ck_character_items_asset_key
        CHECK (char_length(btrim(asset_key)) > 0),

    CONSTRAINT ck_character_items_grade
        CHECK (grade IN ('B', 'A', 'S')),

    CONSTRAINT ck_character_items_category
        CHECK (
            category IN (
                'COLOR',
                'BACKGROUND',
                'EYES',
                'ACCESSORY'
            )
        )
);

-- 등급별 지급 가능한 아이템 검색
CREATE INDEX ix_character_items_active_grade
    ON character_items (grade, id)
    WHERE active = TRUE;


-- 2. 사용자 보유 아이템
CREATE TABLE user_character_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    character_item_id BIGINT NOT NULL,
    acquired_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_user_character_items_user
        FOREIGN KEY (user_id)
        REFERENCES users (id),

    CONSTRAINT fk_user_character_items_character_item
        FOREIGN KEY (character_item_id)
        REFERENCES character_items (id),

    -- 사용자별 동일 아이템 중복 소유 방지
    CONSTRAINT uq_user_character_items_user_item
        UNIQUE (user_id, character_item_id)
);


-- 3. 사용자 현재 장착 아이템
CREATE TABLE user_equipped_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    character_item_id BIGINT NOT NULL,
    category VARCHAR(20) NOT NULL,
    equipped_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_user_equipped_items_user
        FOREIGN KEY (user_id)
        REFERENCES users (id),

    -- 실제 소유하지 않은 아이템 장착 방지
    CONSTRAINT fk_user_equipped_items_owned
        FOREIGN KEY (user_id, character_item_id)
        REFERENCES user_character_items (
            user_id,
            character_item_id
        ),

    -- 장착 슬롯과 실제 아이템 카테고리 일치
    CONSTRAINT fk_user_equipped_items_item_category
        FOREIGN KEY (character_item_id, category)
        REFERENCES character_items (id, category),

    -- 사용자별 카테고리당 최대 한 개
    CONSTRAINT uq_user_equipped_items_user_category
        UNIQUE (user_id, category),

    CONSTRAINT ck_user_equipped_items_category
        CHECK (
            category IN (
                'COLOR',
                'BACKGROUND',
                'EYES',
                'ACCESSORY'
            )
        )
);


-- 4. 사용자별 날짜 단위 보상 정산 완료 기록
CREATE TABLE reward_settlements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    reward_date DATE NOT NULL,
    assigned_todo_count INTEGER NOT NULL,
    completed_todo_count INTEGER NOT NULL,
    completion_rate NUMERIC(5, 2) NOT NULL,
    settled_at TIMESTAMPTZ NOT NULL,

    CONSTRAINT fk_reward_settlements_user
        FOREIGN KEY (user_id)
        REFERENCES users (id),

    -- 실제 지급 여부와 무관하게 하루 한 번만 정산
    CONSTRAINT uq_reward_settlements_user_date
        UNIQUE (user_id, reward_date),

    CONSTRAINT ck_reward_settlements_todo_counts
        CHECK (
            assigned_todo_count >= 0
            AND completed_todo_count >= 0
            AND completed_todo_count <= assigned_todo_count
        ),

    CONSTRAINT ck_reward_settlements_completion_rate
        CHECK (completion_rate BETWEEN 0 AND 100)
);


-- 5. 실제 지급된 보상 아이템 기록
CREATE TABLE reward_grants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    character_item_id BIGINT NOT NULL,
    reward_date DATE NOT NULL,
    reward_grade VARCHAR(10) NOT NULL,
    completion_rate NUMERIC(5, 2) NOT NULL,
    granted_at TIMESTAMPTZ NOT NULL,

    CONSTRAINT fk_reward_grants_user
        FOREIGN KEY (user_id)
        REFERENCES users (id),

    -- 지급 아이템의 실제 등급과 기록된 등급 일치
    CONSTRAINT fk_reward_grants_item_grade
        FOREIGN KEY (character_item_id, reward_grade)
        REFERENCES character_items (id, grade),

    -- 지급 결과는 실제 일일 정산에 속해야 함
    CONSTRAINT fk_reward_grants_settlement
        FOREIGN KEY (user_id, reward_date)
        REFERENCES reward_settlements (user_id, reward_date),

    -- 사용자·날짜·등급별 중복 지급 방지
    CONSTRAINT uq_reward_grants_user_date_grade
        UNIQUE (user_id, reward_date, reward_grade),

    -- 동일 사용자에게 같은 아이템 중복 지급 방지
    CONSTRAINT uq_reward_grants_user_item
        UNIQUE (user_id, character_item_id),

    CONSTRAINT ck_reward_grants_grade
        CHECK (reward_grade IN ('B', 'A', 'S')),

    CONSTRAINT ck_reward_grants_completion_rate
        CHECK (completion_rate BETWEEN 0 AND 100)
);
