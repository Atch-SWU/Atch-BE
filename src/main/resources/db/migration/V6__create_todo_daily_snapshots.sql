
-- TODO 일별 상태 기록
CREATE TABLE todo_daily_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    todo_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    schedule_date DATE NOT NULL,
    status_at_day_end VARCHAR(30) NOT NULL,
    start_at_snapshot TIMESTAMPTZ NOT NULL,
    due_at_snapshot TIMESTAMPTZ NOT NULL,
    completed_at_snapshot TIMESTAMPTZ,
    was_rolled_over BOOLEAN NOT NULL,
    was_overdue BOOLEAN NOT NULL,
    snapshot_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_todo_daily_snapshots_todo
        FOREIGN KEY (todo_id) REFERENCES todos(id),

    CONSTRAINT fk_todo_daily_snapshots_user
        FOREIGN KEY (user_id) REFERENCES users(id),

    CONSTRAINT uq_todo_daily_snapshots_todo_date
        UNIQUE (todo_id, schedule_date),

    CONSTRAINT ck_todo_daily_snapshots_status
        CHECK (status_at_day_end IN ('PENDING', 'IN_PROGRESS', 'PAUSED', 'COMPLETED'))
);

-- 사용자별 일간·주간·월간 Snapshot 조회
CREATE INDEX ix_todo_daily_snapshots_user_date
    ON todo_daily_snapshots (user_id, schedule_date);
