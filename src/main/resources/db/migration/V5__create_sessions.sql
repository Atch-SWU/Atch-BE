
-- SESSION
CREATE TABLE sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    todo_id BIGINT NOT NULL,
    started_at TIMESTAMPTZ NOT NULL,
    ended_at TIMESTAMPTZ,
    duration_seconds INTEGER,
    end_reason VARCHAR(20),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_sessions_todo
        FOREIGN KEY (todo_id) REFERENCES todos(id),

    -- 종료 시각은 시작 시각보다 빠를 수 없음
    CONSTRAINT ck_sessions_time_order
        CHECK (ended_at IS NULL OR ended_at >= started_at),

    -- 0초 집중 구간 허용
    CONSTRAINT ck_sessions_duration_nonnegative
        CHECK (duration_seconds IS NULL OR duration_seconds >= 0),

    -- 종료 사유 Enum 허용값
    CONSTRAINT ck_sessions_end_reason
        CHECK (
            end_reason IS NULL
            OR end_reason IN ('PAUSED', 'COMPLETED', 'SWITCHED')
        ),

    -- 열린 구간과 종료된 구간의 필드 일관성
    CONSTRAINT ck_sessions_end_fields
        CHECK (
            (
                ended_at IS NULL
                AND duration_seconds IS NULL
                AND end_reason IS NULL
            )
            OR
            (
                ended_at IS NOT NULL
                AND duration_seconds IS NOT NULL
                AND end_reason IS NOT NULL
            )
        )
);

-- 동일 Todo에 열린 Session은 최대 하나
CREATE UNIQUE INDEX uq_sessions_open_todo
    ON sessions (todo_id)
    WHERE ended_at IS NULL;

-- Todo별 작업 구간 조회
CREATE INDEX ix_sessions_todo_started
    ON sessions (todo_id, started_at, id);
