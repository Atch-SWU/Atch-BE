-- 전환 대기와 일일 확정 진행 상태. V1~V11 및 기존 데이터는 변경하지 않는다.
CREATE TABLE timer_switch_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id UUID NOT NULL UNIQUE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    source_todo_id BIGINT NOT NULL REFERENCES todos(id) ON DELETE CASCADE,
    target_todo_id BIGINT NOT NULL REFERENCES todos(id) ON DELETE CASCADE,
    source_session_id BIGINT NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
    started_session_id BIGINT REFERENCES sessions(id) ON DELETE CASCADE,
    state VARCHAR(20) NOT NULL,
    requested_at TIMESTAMPTZ NOT NULL,
    ready_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_timer_switch_state CHECK (state IN ('WAITING','STARTED','CANCELLED','EXPIRED')),
    CONSTRAINT ck_timer_switch_distinct CHECK (source_todo_id <> target_todo_id),
    CONSTRAINT ck_timer_switch_time CHECK (ready_at >= requested_at AND expires_at > ready_at),
    CONSTRAINT ck_timer_switch_started CHECK ((state = 'STARTED') = (started_session_id IS NOT NULL))
);
CREATE UNIQUE INDEX uq_timer_switch_waiting_user ON timer_switch_requests(user_id) WHERE state = 'WAITING';
CREATE INDEX ix_timer_switch_receipt ON timer_switch_requests(user_id, source_session_id, target_todo_id, id DESC);

CREATE TABLE user_daily_settlement_states (
    user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    tracking_started_on DATE NOT NULL,
    next_settlement_date DATE NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_daily_settlement_date CHECK (next_settlement_date >= tracking_started_on)
);
CREATE INDEX ix_daily_settlement_pending ON user_daily_settlement_states(next_settlement_date, user_id);

