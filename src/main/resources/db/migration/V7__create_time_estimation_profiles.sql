
-- 사용자별 시간 예측 보정 프로필
CREATE TABLE time_estimation_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    duration_correction_factor DOUBLE PRECISION NOT NULL,
    sample_count INTEGER NOT NULL,
    log_ratio_stddev DOUBLE PRECISION,
    underestimation_rate DOUBLE PRECISION NOT NULL,
    profile_reliability_score DOUBLE PRECISION NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_time_estimation_profiles_user
        FOREIGN KEY (user_id) REFERENCES users(id),

    CONSTRAINT uq_time_estimation_profiles_user
        UNIQUE (user_id),

    CONSTRAINT ck_time_estimation_profiles_factor
        CHECK (duration_correction_factor > 0),

    CONSTRAINT ck_time_estimation_profiles_sample_count
        CHECK (sample_count >= 0),

    CONSTRAINT ck_time_estimation_profiles_stddev
        CHECK (log_ratio_stddev IS NULL OR log_ratio_stddev >= 0),

    CONSTRAINT ck_time_estimation_profiles_underestimation_rate
        CHECK (underestimation_rate BETWEEN 0 AND 1),

    CONSTRAINT ck_time_estimation_profiles_reliability
        CHECK (profile_reliability_score BETWEEN 0 AND 1)
);
