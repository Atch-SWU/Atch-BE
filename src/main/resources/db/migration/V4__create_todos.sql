CREATE TABLE todos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    recurrence_rule_id BIGINT,
    recurrence_occurrence_at TIMESTAMPTZ,
    title VARCHAR(200) NOT NULL,
    source_task_name VARCHAR(200),
    memo TEXT,
    start_at TIMESTAMPTZ NOT NULL,
    due_at TIMESTAMPTZ NOT NULL,
    current_schedule_date DATE NOT NULL,
    all_day BOOLEAN NOT NULL,
    user_estimated_duration_minutes INTEGER NOT NULL,
    user_estimate_source VARCHAR(30) NOT NULL,
    ai_estimated_duration_minutes INTEGER,
    selected_estimate_type VARCHAR(20) NOT NULL,
    status VARCHAR(30) NOT NULL,
    completed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMPTZ,

    CONSTRAINT fk_todos_user
        FOREIGN KEY (user_id) REFERENCES users(id),

    CONSTRAINT ck_todos_title_not_blank
        CHECK (char_length(btrim(title)) > 0),

    CONSTRAINT ck_todos_schedule_order
        CHECK (due_at > start_at),

    CONSTRAINT ck_todos_user_estimate_positive
        CHECK (user_estimated_duration_minutes > 0),

    CONSTRAINT ck_todos_ai_estimate_positive
        CHECK (ai_estimated_duration_minutes IS NULL
            OR ai_estimated_duration_minutes > 0),

    CONSTRAINT ck_todos_user_estimate_source
        CHECK (user_estimate_source IN ('USER_INPUT', 'RECURRENCE_TEMPLATE')),

    CONSTRAINT ck_todos_selected_estimate_type
        CHECK (selected_estimate_type IN ('USER', 'AI')),

    CONSTRAINT ck_todos_ai_selection
        CHECK (selected_estimate_type <> 'AI'
            OR ai_estimated_duration_minutes IS NOT NULL),

    CONSTRAINT ck_todos_status
        CHECK (status IN ('PENDING', 'IN_PROGRESS', 'PAUSED', 'COMPLETED')),

    CONSTRAINT ck_todos_recurrence_pair
        CHECK (
            (recurrence_rule_id IS NULL AND recurrence_occurrence_at IS NULL)
            OR
            (recurrence_rule_id IS NOT NULL AND recurrence_occurrence_at IS NOT NULL)
        ),

    -- 이월된 배정 날짜는 검사하지 않고 원래 일정의 서울 경계만 검사
    CONSTRAINT ck_todos_all_day_boundaries
        CHECK (
            NOT all_day
            OR (
                (start_at AT TIME ZONE 'Asia/Seoul')::time = TIME '00:00'
                AND (due_at AT TIME ZONE 'Asia/Seoul')
                    = (start_at AT TIME ZONE 'Asia/Seoul') + INTERVAL '1 day'
            )
        )
);

-- recurrence_rules FK는 해당 테이블을 생성하는 V10에서 추가
-- 논리 삭제된 회차도 유지하여 자동 재생성을 방지
CREATE UNIQUE INDEX uq_todos_recurrence_occurrence
    ON todos (recurrence_rule_id, recurrence_occurrence_at)
    WHERE recurrence_rule_id IS NOT NULL;

CREATE INDEX ix_todos_user_schedule_active
    ON todos (user_id, current_schedule_date, start_at, id)
    WHERE deleted_at IS NULL;

CREATE INDEX ix_todos_user_status_active
    ON todos (user_id, status, start_at, id)
    WHERE deleted_at IS NULL;
