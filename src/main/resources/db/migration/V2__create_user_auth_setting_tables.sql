
-- USER
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nickname VARCHAR(8) NOT NULL,
    bio VARCHAR(255),
    onboarding_completed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_users_nickname_length
        CHECK (char_length(nickname) BETWEEN 2 AND 8)
);

-- AUTH_ACCOUNT
CREATE TABLE auth_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    provider VARCHAR(20) NOT NULL,
    email VARCHAR(320),
    password_hash VARCHAR(255),
    provider_user_id VARCHAR(255),
    last_login_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_auth_accounts_user
        FOREIGN KEY (user_id) REFERENCES users(id),

    CONSTRAINT ck_auth_accounts_provider
        CHECK (provider IN ('LOCAL', 'GOOGLE', 'KAKAO', 'APPLE')),

    -- LOCAL과 SOCIAL의 필수 필드 구분
    CONSTRAINT ck_auth_accounts_fields
        CHECK (
            (
                provider = 'LOCAL'
                AND email IS NOT NULL
                AND password_hash IS NOT NULL
                AND provider_user_id IS NULL
            )
            OR
            (
                provider IN ('GOOGLE', 'KAKAO', 'APPLE')
                AND provider_user_id IS NOT NULL
                AND password_hash IS NULL
            )
        )
);

-- LOCAL 이메일 중복 방지
CREATE UNIQUE INDEX ux_auth_accounts_local_email
    ON auth_accounts (LOWER(email))
    WHERE provider = 'LOCAL';

-- 동일 소셜 제공자 내 사용자 ID 중복 방지
CREATE UNIQUE INDEX ux_auth_accounts_social_identity
    ON auth_accounts (provider, provider_user_id)
    WHERE provider IN ('GOOGLE', 'KAKAO', 'APPLE');

-- 사용자당 LOCAL 인증 수단 최대 1개
CREATE UNIQUE INDEX ux_auth_accounts_user_local
    ON auth_accounts (user_id)
    WHERE provider = 'LOCAL';

-- 사용자당 SOCIAL 인증 수단 최대 1개
CREATE UNIQUE INDEX ux_auth_accounts_user_social
    ON auth_accounts (user_id)
    WHERE provider IN ('GOOGLE', 'KAKAO', 'APPLE');

-- USER_SETTING
CREATE TABLE user_settings (
    user_id BIGINT PRIMARY KEY,
    task_switch_restriction_enabled BOOLEAN NOT NULL,
    task_switch_wait_minutes INTEGER NOT NULL DEFAULT 10,
    repeat_recommendation_enabled BOOLEAN NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_user_settings_user
        FOREIGN KEY (user_id) REFERENCES users(id),

    CONSTRAINT ck_user_settings_wait_minutes
        CHECK (task_switch_wait_minutes > 0)
);
