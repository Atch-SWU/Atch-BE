-- 초안·성공 사용 이력·최종 생성 재전송을 분리한다. 기존 Todo/예상시간은 변경하지 않는다.
CREATE TABLE ai_drafts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    draft_id UUID NOT NULL UNIQUE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    todo_id BIGINT UNIQUE REFERENCES todos(id) ON DELETE CASCADE,
    parent_id BIGINT,
    expires_at TIMESTAMPTZ NOT NULL,
    finalized_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_ai_draft_owner UNIQUE(id, user_id),
    CONSTRAINT fk_ai_draft_parent_owner FOREIGN KEY(parent_id, user_id)
        REFERENCES ai_drafts(id, user_id) ON DELETE CASCADE,
    CONSTRAINT ck_ai_draft_parent CHECK(parent_id IS NULL OR parent_id <> id)
);
CREATE INDEX ix_ai_drafts_owner ON ai_drafts(user_id, created_at DESC);

CREATE TABLE ai_operations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    draft_id BIGINT NOT NULL REFERENCES ai_drafts(id) ON DELETE CASCADE,
    feature VARCHAR(30) NOT NULL,
    state VARCHAR(30) NOT NULL,
    input_hash CHAR(64),
    attempt_id UUID,
    lease_until TIMESTAMPTZ,
    succeeded_at TIMESTAMPTZ,
    as_of TIMESTAMPTZ,
    result_payload JSONB,
    model_name VARCHAR(100),
    prompt_version VARCHAR(50),
    attempt_count INTEGER NOT NULL DEFAULT 0,
    error_category VARCHAR(50),
    CONSTRAINT uq_ai_operation_feature UNIQUE(draft_id, feature),
    CONSTRAINT ck_ai_operation_feature CHECK(feature IN ('DECOMPOSITION','TIME_PREDICTION')),
    CONSTRAINT ck_ai_operation_state CHECK(state IN ('IN_PROGRESS','SUCCEEDED','RETRYABLE_FAILURE','LEGACY_UNKNOWN')),
    CONSTRAINT ck_ai_operation_hash CHECK(input_hash IS NULL OR input_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_ai_operation_result_object CHECK(result_payload IS NULL OR jsonb_typeof(result_payload)='object'),
    CONSTRAINT ck_ai_operation_attempts CHECK(attempt_count >= 0),
    CONSTRAINT ck_ai_operation_success CHECK(state <> 'SUCCEEDED' OR
        (input_hash IS NOT NULL AND result_payload IS NOT NULL AND succeeded_at IS NOT NULL AND as_of IS NOT NULL)),
    CONSTRAINT ck_ai_operation_reservation CHECK(state <> 'IN_PROGRESS' OR
        (input_hash IS NOT NULL AND attempt_id IS NOT NULL AND lease_until IS NOT NULL))
);
CREATE INDEX ix_ai_operations_expired ON ai_operations(lease_until) WHERE state='IN_PROGRESS';

CREATE TABLE ai_creation_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    draft_id BIGINT NOT NULL UNIQUE,
    creation_request_id UUID NOT NULL,
    request_hash CHAR(64) NOT NULL CHECK(request_hash ~ '^[0-9a-f]{64}$'),
    result_payload JSONB NOT NULL CHECK(jsonb_typeof(result_payload)='object'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_ai_creation_owner FOREIGN KEY(draft_id, user_id)
        REFERENCES ai_drafts(id, user_id) ON DELETE CASCADE,
    CONSTRAINT uq_ai_creation_request UNIQUE(user_id, creation_request_id)
);

-- 기존 제안값의 Claude 성공 여부는 알 수 없다. 원본을 보존하고 재호출만 보수적으로 제한한다.
-- 최초 조회 전에 일반 편집으로 AI 값이 지워져도 이관 시점의 이력은 남는다.
INSERT INTO ai_drafts(draft_id, user_id, todo_id, expires_at)
SELECT gen_random_uuid(), user_id, id, CURRENT_TIMESTAMP + INTERVAL '1 day'
FROM todos WHERE ai_estimated_duration_minutes IS NOT NULL;

INSERT INTO ai_operations(draft_id, feature, state)
SELECT id, 'TIME_PREDICTION', 'LEGACY_UNKNOWN' FROM ai_drafts;
